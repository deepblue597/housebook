#!/usr/bin/env node
// Regenerate the typed API client from the backend's OpenAPI spec.
//
//   pnpm gen:api      dump apps/api's OpenAPI spec -> src/api/openapi.json -> src/api/schema.gen.ts
//   pnpm check:api    same, but fail if the committed files differ (DESIGN 15.15, CI contract check)
//
// The spec comes straight from the FastAPI app object (no running server needed), via uv.
import { execFileSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import openapiTS, { astToString } from 'openapi-typescript';

const here = dirname(fileURLToPath(import.meta.url));
const webDir = resolve(here, '..');
const apiDir = resolve(webDir, '../api');
const specPath = join(webDir, 'src/api/openapi.json');
const typesPath = join(webDir, 'src/api/schema.gen.ts');
const check = process.argv.includes('--check');

const PY = `
import json, sys
from housebook.api.app import create_app
from housebook.config import Settings
app = create_app(Settings.from_env({"HOUSEBOOK_DATA_DIR": sys.argv[1]}))
print(json.dumps(app.openapi(), indent=2, ensure_ascii=False))
`;

// create_app only wires things up (scanning happens at startup), but Settings wants a real dir.
const scratch = mkdtempSync(join(tmpdir(), 'housebook-openapi-'));
let specText;
try {
  specText = execFileSync(
    'uv',
    ['run', '--quiet', '--project', apiDir, 'python', '-c', PY, scratch],
    {
      cwd: apiDir,
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'inherit'],
    },
  );
} finally {
  rmSync(scratch, { recursive: true, force: true });
}

const spec = JSON.parse(specText);
const header =
  '// Generated by scripts/gen-api.mjs from the backend OpenAPI spec. Do not edit.\n' +
  '// Regenerate with `pnpm gen:api`.\n\n';
const types = header + astToString(await openapiTS(spec));

const outputs = [
  [specPath, specText],
  [typesPath, types],
];

if (check) {
  const stale = outputs.filter(([path, text]) => {
    try {
      return readFileSync(path, 'utf8') !== text;
    } catch {
      return true;
    }
  });
  if (stale.length) {
    console.error(
      `API client is stale: ${stale.map(([p]) => p).join(', ')}\nRun \`pnpm gen:api\`.`,
    );
    process.exit(1);
  }
  console.log('API client is up to date.');
} else {
  for (const [path, text] of outputs) writeFileSync(path, text);
  console.log(`wrote ${specPath}\nwrote ${typesPath}`);
}
